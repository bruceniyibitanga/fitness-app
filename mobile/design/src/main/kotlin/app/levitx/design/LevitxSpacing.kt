package app.levitx.design

import androidx.compose.ui.unit.dp

/** Spacing steps. Use these instead of one-off numbers so layouts line up. */
object LevitxSpacing {
    /** 4 dp: between a label and its value. */
    val XSmall = 4.dp

    /** 8 dp: between related items. */
    val Small = 8.dp

    /** 16 dp: between groups, and phone screen edges. */
    val Medium = 16.dp

    /** 24 dp: between sections. */
    val Large = 24.dp

    /** 40 dp: above a screen's main content. */
    val XLarge = 40.dp
}
